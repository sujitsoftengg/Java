package Ch01_Basics.Lesson;

public class R13_WhileLoop {
    static void main(String[] args) {
        System.out.println("While Loop");

        int i = 1;

        while (i <= 100){
            System.out.println("No. " + i);
            i++;
        }

        int j =500;
        while (j > 200){
            System.out.println("No. " + j);
            j--;
        }

    }
}
