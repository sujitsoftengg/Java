package Ch01_Basics.Lesson;

public class R06_ArithmeticOp {
    static void main(String[] args) {

        // Arithmetic Operator ( +, -, *, /, %)

        int numA = 5;
        int numB = 2;

        System.out.println(numA + numB);
        System.out.println(numA - numB);
        System.out.println(numA * numB);
        System.out.println(numA / numB);
        System.out.println(numA % numB);


    }
}
