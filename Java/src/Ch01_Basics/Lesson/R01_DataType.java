package Ch01_Basics.Lesson;
public class R01_DataType {
    static void main(String[] args) {
        String myName = "Sujit Tomar";
        boolean isPass = true;
        // double can contain after point 6 to 7 digit (4 bytes)
        double markPer = 89.65;
        char initial = 'S';
        int myAge = 25;
        // Float can contain after point till 15 digit (8 bytes)
        float myHeight = 5.71f;

        System.out.println(myName);
        System.out.println(isPass);
        System.out.println(markPer);
        System.out.println(initial);
        System.out.println(myAge);
        System.out.println(myHeight);

    }

}