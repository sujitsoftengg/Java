package Ch11_Encapsulation.Chalanges.com.example.geometry;

public class Rectangle {
    double length;
    double width;

    public Rectangle(){

    }

    public Rectangle(double length, double width){
        this.length = length;
        this.width = width;
    }

    public double getLength(){
        return length;
    }

    public double getWidth(){
        return width;
    }


}
